import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {getTransactionDecoder} from '@solana/kit';
import {verifyPublicReceiptIntegrity,verifyRoutePlanIntegrity,sha256Hex} from '../veil-core-review/tamassol_veil_router_v3/dist/index.js';
import {POLICY} from './veil-helius-adapter.mjs';
const root='router-evidence';
const report=JSON.parse(await readFile(`${root}/result.json`,'utf8'));
const receipt=JSON.parse(await readFile(`${root}/receipt.json`,'utf8'));
const prepared=JSON.parse(await readFile(`${root}/prepared-route.json`,'utf8'));
prepared.intent.amountBaseUnits=BigInt(prepared.intent.amountBaseUnits);
prepared.intent.feeCeilingBaseUnits=BigInt(prepared.intent.feeCeilingBaseUnits);
prepared.selectedQuote.estimatedFeeBaseUnits=BigInt(prepared.selectedQuote.estimatedFeeBaseUnits);
assert.equal(report.status,'passed');
assert(await verifyPublicReceiptIntegrity(receipt));
assert(await verifyRoutePlanIntegrity(prepared,POLICY));
assert.equal(receipt.routePlanHash,prepared.plan.routePlanHash);
assert.equal(receipt.intentHash,prepared.intentHash);
assert.equal(receipt.providerEvidenceHash,await sha256Hex(JSON.stringify(report.providerEvidence)));
assert.equal(receipt.chainSignature,report.signature);
async function rpc(method,params=[]){const r=await fetch('https://api.devnet.solana.com',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:1,method,params}),signal:AbortSignal.timeout(20000)});const body=await r.json();assert(!body.error,`Public RPC ${method} failed`);return body.result;}
assert.equal(await rpc('getGenesisHash'),'EtWTRABZaYq6iMfeYKouRu166VU2xqa1wcaWoxPkrZBG');
const status=(await rpc('getSignatureStatuses',[[report.signature],{searchTransactionHistory:true}])).value[0];
assert(status && status.err===null);assert.equal(status.confirmationStatus,'finalized');
const tx=await rpc('getTransaction',[report.signature,{encoding:'base64',commitment:'finalized',maxSupportedTransactionVersion:1}]);
assert(tx && tx.meta.err===null);assert.equal(String(tx.slot),report.providerEvidence.slot);assert.equal(String(tx.meta.fee),report.networkFeeLamports);
const decoded=getTransactionDecoder().decode(Buffer.from(tx.transaction[0],'base64'));
assert.equal(createHash('sha256').update(decoded.messageBytes).digest('hex'),report.transactionMessageHash);
const verification={status:'passed',readOnly:true,network:'devnet',confirmation:'finalized',signature:report.signature,slot:tx.slot,feeLamports:tx.meta.fee,receiptIntegrity:true,routeIntegrity:true,evidenceCommitment:true,onChainMessageMatchesSignedMessage:true,checkedAt:new Date().toISOString(),limits:'Hashes prove consistency, not third-party attestation. Amounts verified separately by local decryption; software approval only.'};
await writeFile(`${root}/independent-verification.json`,JSON.stringify(verification,null,2));
console.log(JSON.stringify(verification,null,2));
